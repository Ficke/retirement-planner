#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UserProfile {
    /// Date of birth, ISO. Age and the RMD / Social Security birth-year cohort
    /// are both derived from it, so they can never disagree.
    #[serde(rename = "birthDate")]
    pub birth_date: String,
    pub state: State,
    #[serde(rename = "filingStatus")]
    pub filing_status: FilingStatus,
    #[serde(rename = "retirementAge")]
    pub retirement_age: u32,
    #[serde(rename = "currentSalary")]
    pub current_salary: f64,
    #[serde(rename = "salaryGrowthRate")]
    pub salary_growth_rate: f64,
    #[serde(rename = "currentSpending")]
    pub current_spending: f64,
    #[serde(rename = "workingSpendingGrowthRate", default)]
    pub working_spending_growth_rate: f64,
    #[serde(rename = "retirementSpending", alias = "desiredSpending")]
    pub retirement_spending: f64,
    #[serde(rename = "retirementSpendingGrowthRate", alias = "spendingGrowthRate")]
    pub retirement_spending_growth_rate: f64,
    #[serde(rename = "lifeExpectancy")]
    pub life_expectancy: u32,
    /// Healthcare in retirement, carried separately from `current_spending`
    /// because it steps down at Medicare and grows faster than everything else.
    #[serde(rename = "retirementHealthcare", default)]
    pub retirement_healthcare: RetirementHealthcare,
    /// Long-term care, drawn per path rather than budgeted, so it is a
    /// distribution rather than an annual amount.
    #[serde(rename = "longTermCare", default)]
    pub long_term_care: LongTermCare,
    #[serde(rename = "asOfDate")]
    pub as_of_date: String,
}

/// Retirement healthcare, which is a step at Medicare eligibility rather than a
/// share of spending. Premiums and out-of-pocket costs are separate because
/// Medicare, and later any subsidy or surcharge, moves only the premium.
///
/// All figures are household totals in real dollars. A request that predates
/// this field gets zeros, which reproduces the projection it would have had.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct RetirementHealthcare {
    #[serde(rename = "preMedicarePremium", default)]
    pub pre_medicare_premium: f64,
    #[serde(rename = "medicarePremium", default)]
    pub medicare_premium: f64,
    #[serde(rename = "outOfPocket", default)]
    pub out_of_pocket: f64,
    #[serde(rename = "realGrowthRate", default)]
    pub real_growth_rate: f64,
}

/// Long-term care, whose cost is a lifetime out-of-pocket draw rather than an
/// annual budget line. `cost_multiplier` scales the drawn amount for location
/// and care level; income is already carried by the distribution itself.
///
/// Unlike the healthcare fields, an absent value is not a no-op: the model is
/// on for every plan, including requests that predate it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LongTermCare {
    #[serde(rename = "enabled", default = "default_ltc_enabled")]
    pub enabled: bool,
    #[serde(rename = "costMultiplier", default = "default_ltc_cost_multiplier")]
    pub cost_multiplier: f64,
}

impl Default for LongTermCare {
    fn default() -> Self {
        Self {
            enabled: default_ltc_enabled(),
            cost_multiplier: default_ltc_cost_multiplier(),
        }
    }
}

fn default_ltc_enabled() -> bool {
    true
}

fn default_ltc_cost_multiplier() -> f64 {
    1.0
}


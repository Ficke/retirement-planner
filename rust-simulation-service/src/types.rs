#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PathProjection {
    pub year: u32,
    pub age: u32,
    #[serde(rename = "portfolioValue")]
    pub portfolio_value: f64,
    pub income: f64,
    pub spending: f64,
    pub taxes: f64,
    pub savings: f64,
    #[serde(rename = "socialSecurityBenefit")]
    pub social_security_benefit: f64,
    #[serde(rename = "isRetired")]
    pub is_retired: bool,
    #[serde(rename = "withdrawalTaxable")]
    pub withdrawal_taxable: f64,
    #[serde(rename = "withdrawalTraditional")]
    pub withdrawal_traditional: f64,
    #[serde(rename = "withdrawalRoth")]
    pub withdrawal_roth: f64,
    #[serde(rename = "rmdAmount")]
    pub rmd_amount: f64,
    /// Pre-tax dollars moved Traditional -> Roth this year. An internal
    /// transfer, so it is no part of `spending` or the withdrawal totals; only
    /// the tax it adds reaches `taxes`.
    #[serde(rename = "rothConversion", default)]
    pub roth_conversion: f64,
    #[serde(rename = "depositTaxable")]
    pub deposit_taxable: f64,
    #[serde(rename = "depositTraditional")]
    pub deposit_traditional: f64,
    #[serde(rename = "depositRoth")]
    pub deposit_roth: f64,
    #[serde(rename = "depositHSA")]
    pub deposit_hsa: f64,
    #[serde(rename = "withdrawalHSA")]
    pub withdrawal_hsa: f64,
    /// Funded recurring retirement healthcare for the year, excluding any
    /// long-term-care episode. Part of the same `spending` total and zero while
    /// working, where healthcare sits inside `current_spending`.
    #[serde(rename = "healthcareCost")]
    pub healthcare_cost: f64,
    /// Funded long-term-care spending for the year, reported separately from
    /// recurring healthcare while remaining part of `spending`.
    #[serde(rename = "longTermCareCost", default)]
    pub long_term_care_cost: f64,
    #[serde(rename = "insufficientFunds")]
    pub insufficient_funds: bool,
}

